/** Builds VERIFY.md: every real-world figure or claim a human should fact-check. */
import type { GameContent, Locale } from './types';
import { buildIndex } from '../engine/contentIndex';

function show(v: unknown): string {
  if (Array.isArray(v)) return v.map((b: { from: number; rate: number }) => `${(b.rate * 100).toFixed(0)}% from $${b.from.toLocaleString('en-US')}`).join('; ');
  if (typeof v === 'number' && Number.isInteger(v) && v >= 1900 && v <= 2100) return String(v);
  if (typeof v === 'number') return Math.abs(v) < 1 && v !== 0 ? `${+(v * 100).toFixed(3)}%` : v.toLocaleString('en-US');
  return String(v);
}

export function buildVerifyMd(content: GameContent, locale: Locale): string {
  const facts = Object.entries(locale.facts);
  const unverified = facts.filter(([, f]) => ['law', 'fact', 'statistic'].includes(f.kind) && !f.lastVerified);
  const verified = facts.filter(([, f]) => ['law', 'fact', 'statistic'].includes(f.kind) && f.lastVerified);
  const illustrative = facts.filter(([, f]) => f.kind === 'illustrative' || f.kind === 'convention');
  const idx = buildIndex(content);
  const scenes = [...idx.scenes.values()].filter((r) => r.scene.needsVerification);
  const out: string[] = [
    '# VERIFY.md — things a human needs to fact-check',
    '',
    '<!-- Generated by `npm run verify:list`. Do not edit by hand: change the locale pack or the scene, then regenerate. -->',
    '',
    `Locale pack: \`locales/${locale.id}.yaml\` (${locale.name}).`,
    '',
    'To mark a figure as checked, set its `lastVerified: YYYY-MM-DD` in the locale pack (and fix the value or source if needed).',
    'To clear a scene, set `needsVerification: false` once its claims and sources are confirmed.',
    '',
    `## 1. Laws, facts and statistics not yet verified (${unverified.length})`,
    '',
    '| Key | Value | What it is | Source to check |',
    '|---|---|---|---|',
    ...unverified.map(([k, f]) => `| \`${k}\` | ${show(f.value)} | ${f.label}${f.note ? ` — ${f.note}` : ''} | ${f.source ?? '—'} |`),
    '',
    `## 2. Scene claims to verify (${scenes.length})`,
    '',
    'These scenes state how a rule or product works. Check the explanation text against the listed sources.',
    '',
  ];
  for (const r of scenes) {
    out.push(`### \`${r.scene.id}\` — ${r.scene.title ?? ''}`, '', `> ${r.scene.explanation.replace(/\s+/g, ' ')}`, '');
    for (const s of r.scene.sources) out.push(`- ${s.title}${s.publisher ? ` (${s.publisher})` : ''}${s.url ? ` — ${s.url}` : ''}`);
    out.push('');
  }
  out.push(
    `## 3. Illustrative values and conventions — sanity-check only (${illustrative.length})`,
    '',
    'These are labeled "illustrative" in the game. They should be realistic, not exact.',
    '',
    '| Key | Value | What it is |',
    '|---|---|---|',
    ...illustrative.map(([k, f]) => `| \`${k}\` | ${show(f.value)} | ${f.label}${f.note ? ` — ${f.note}` : ''} |`),
    '',
  );
  if (verified.length) {
    out.push(`## 4. Already verified (${verified.length})`, '', ...verified.map(([k, f]) => `- \`${k}\` — ${f.label} (checked ${f.lastVerified})`), '');
  }
  return out.join('\n');
}
